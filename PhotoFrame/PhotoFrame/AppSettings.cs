namespace PhotoFrame
{
    /// <summary>
    /// Неизменяемые параметры сборки. Всё, что пользователь может поменять на самой
    /// рамке, живёт в <see cref="FrameSettings"/>.
    /// </summary>
    public static class AppSettings
    {
        /// <summary>Разрешение экрана рамки — подтверждено на устройстве через "wm size".</summary>
        public const int FrameWidthPixels = 1280;

        /// <summary>Высота экрана рамки в пикселях.</summary>
        public const int FrameHeightPixels = 800;

        /// <summary>
        /// Верхняя граница на число снимков, скачиваемых из общего альбома.
        /// </summary>
        /// <remarks>
        /// Ограничение имеет смысл только здесь: каждый кадр из альбома — это HTTP-запрос
        /// и место на диске, и без предела первая синхронизация огромного альбома заняла бы
        /// часы. Локальные папки таким пределом НЕ ограничены: файлы не копируются, список
        /// путей стоит доли мегабайта, а обрезка означала бы, что дальняя часть
        /// фотоплёнки не покажется никогда.
        ///
        /// Когда предел достигнут, об этом сообщается в статусе, а не замалчивается.
        /// Значение задаётся в настройках; здесь только величина по умолчанию.
        /// </remarks>
        public const int DefaultAlbumPhotoLimit = 2000;
    }
}
