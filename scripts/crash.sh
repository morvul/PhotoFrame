#!/usr/bin/env bash
#
# Всё, что осталось после падения.
#
# Порядок вывода не случаен: сперва управляемое исключение (у него читаемый стек),
# затем нативный сигнал, затем пульс — по нему видно, было ли падение связано
# с памятью, и что рамка делала в последние минуты.

. "$(dirname "$0")/common.sh"

echo "=== Падения (буфер crash) ============================================"
crashes="$(frame logcat -d -b crash -v time 2>/dev/null | tr -d '\r')"
if [ -z "$crashes" ]; then
    echo "пусто — с последней загрузки падений не было"
else
    echo "$crashes" | tail -40
fi

echo
echo "=== Жалобы вендорного декодера ======================================="
# Их бывает по несколько за минуту и в норме. Признак беды — сотни подряд:
# очередь декодера перестала разбираться, и следом приложение падало.
count="$(frame logcat -d 2>/dev/null | grep -c "stream list full" || true)"
echo "строк «stream list full wait» с загрузки: $count"

echo
echo "=== Пульс перед падением ============================================="
frame shell "tail -12 $FRAME_LOG" 2>/dev/null | tr -d '\r' \
    || echo "журнал состояния недоступен"

echo
echo "Подсказка: в строках пульса смотрите free (память), cpu (прирост за минуту)"
echo "и slide/clip — на чём рамка остановилась."
